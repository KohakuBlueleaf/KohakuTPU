"""The machine a program targets: every hardware fact of one image, read from
``machines/<name>.json`` (generated by ``scripts/py/machine`` from the build
config, board, RTL and firmware). The stack reads facts here by path, e.g.
``m.vc.lanes`` or ``m.get("vc.lanes")``, never as constants of its own."""

import hashlib
import json
import os
from functools import cache
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[5]
_DEFAULT_MACHINES = Path(os.environ.get("KTPU_MACHINES", ROOT / "machines"))
#: Where machine files live; ``KTPU_MACHINES`` names another directory.
MACHINES = _DEFAULT_MACHINES
#: The schema definition: ktpu-machine's typed schema, one file per section.
SCHEMA_DIR = ROOT / "software/rust/crates/ktpu-machine/src/schema"


def schema_version_of(texts: list[str]) -> str:
    """The version of a schema definition: the first 16 hex digits of sha256
    over `texts` with ``//`` comments and all whitespace removed, one line per
    file (ktpu-machine ``schema_version_of``, the same computation)."""
    files = [
        "".join("".join(line.split("//")[0].split()) for line in t.splitlines())
        for t in texts
    ]
    return hashlib.sha256("\n".join(files).encode()).hexdigest()[:16]


@cache
def schema_version() -> str:
    """The schema version of the definition in the tree: every machine file
    is written for it, and a file of another version is refused."""
    paths = sorted(SCHEMA_DIR.glob("*.rs"), key=lambda p: p.name)
    return schema_version_of([p.read_text(encoding="utf-8") for p in paths])


class Machine:
    """A section of a machine file; attribute access walks into sections."""

    def __init__(self, data: dict, path: str = "", sources: dict | None = None):
        self._data = data
        self._path = path
        self._sources = sources or {}

    def __getattr__(self, key: str) -> Any:
        if key.startswith("_"):
            raise AttributeError(key)
        try:
            value = self._data[key]
        except KeyError:
            raise AttributeError(f"machine has no {self._path}{key}") from None
        return (
            Machine(value, f"{self._path}{key}.", self._sources)
            if isinstance(value, dict)
            else value
        )

    def get(self, path: str) -> Any:
        """The value at dotted `path`."""
        node = self
        for key in path.split("."):
            node = getattr(node, key)
        return node

    def source(self, path: str) -> str:
        """Where the fact at `path` comes from (a file:line or a derivation)."""
        return self._sources[path]

    def dict(self) -> dict:
        return self._data


def names() -> list[str]:
    """Every machine file there is."""
    return sorted(p.stem for p in MACHINES.glob("*.json") if p.stem != "measured")


@cache
def _load_default(name: str, ver: str) -> Machine:
    path = _DEFAULT_MACHINES / f"{name}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"no machine file {name!r} in {_DEFAULT_MACHINES}; have {names()}"
        )
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("schema") != ver:
        raise ValueError(
            f"{path.name}: schema {doc.get('schema')!r}, the tree's schema is "
            f"{ver}: regenerate the machine files (scripts/py/machine)"
        )
    return Machine(doc["machine"], "", doc["sources"])


def load(name: str) -> Machine:
    """The machine file `name` (a board name such as ``multimesh_v9t6``)."""
    if MACHINES == _DEFAULT_MACHINES:
        return _load_default(name, schema_version())
    path = MACHINES / f"{name}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"no machine file {name!r} in {MACHINES}; have {names()}"
        )
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("schema") != schema_version():
        raise ValueError(
            f"{path.name}: schema {doc.get('schema')!r}, the tree's schema is "
            f"{schema_version()}: regenerate the machine files (scripts/py/machine)"
        )
    return Machine(doc["machine"], "", doc["sources"])


__all__ = [
    "MACHINES",
    "Machine",
    "load",
    "names",
    "schema_version",
    "schema_version_of",
]
