"""A1: doorbell ping-pong between every ordered pair of sysnodes, fenced and plain
rings. The pong side rings READY first, so the ping side's package starts its
`ROUNDS` round trips with both sides up; each side stores its round count."""

import itertools

import numpy as np

from h.gen import Module, Spec

#: Round trips a package, the signal slots used, and each fn's (count) output.
ROUNDS = (1, 8)
READY, PING = 1, 2

HEAD = """# Generated by h/gen/a1.py.
target ktpu.v9
"""


def side(me: int, peer: int, rounds: int, plain: str, first: bool, at: int) -> str:
    """One sysnode's block: the ping side waits READY, then rings and waits;
    the pong side rings READY, then waits and rings."""
    ring = f"ring mesh={peer} slot={PING}{plain}"
    wait = f"wait slot {PING} n=1 consume"
    start = (
        f"wait slot {READY} n=1 consume" if first else f"ring mesh={peer} slot={READY}"
    )
    one, two = (ring, wait) if first else (wait, ring)
    return f"""
    node {me}
        {start}
        r1 = set 0
        r2 = set {rounds}
        label trip
        {one}
        {two}
        r1 = add r1, 1
        goto trip if r1 < r2
        store count + {at} <- r1"""


def fn(i: int, j: int, rounds: int, plain: bool) -> tuple[str, str]:
    name = f"a1_{i}{j}_{'plain' if plain else 'fenced'}_k{rounds}"
    flag = " plain" if plain else ""
    body = side(i, j, rounds, flag, True, 0) + side(j, i, rounds, flag, False, 8)
    return name, f"\nfn {name}.l1(count: u64[2] @dram){body}\n"


def generate(sysnodes: tuple[int, ...], board: str) -> Module:
    text, specs = HEAD, {}
    for (i, j), rounds, plain in itertools.product(
        itertools.permutations(sysnodes, 2), ROUNDS, (False, True)
    ):
        name, src = fn(i, j, rounds, plain)
        text += src
        specs[name] = Spec(
            ("count",), lambda _, k=rounds: {"count": np.full(2, k, np.uint64)}
        )
    return Module(text, specs)
