"""The memory grid as L1 source: footprint by stride by direction by agent, agents at
once, and one walk per Xache home (16 KB rotation over four channels). anchors.py runs
the module it writes.

    python software/tests/perf/memgrid.py OUT.ktpu
"""

import pathlib
import sys

KB, MB = 1 << 10, 1 << 20
FOOTPRINTS = (64 * KB, 256 * KB, MB, 4 * MB, 16 * MB, 64 * MB)
STRIDES = (32, 64, 128, 256, 1024, 4096, 16 * KB, 64 * KB)
LINE = 32
HOMES = 4
ROTATION = 16 * KB

HEAD = """# Generated by memgrid.py.
target ktpu.v9
"""


def burst(stride: int) -> int:
    """Words a load: 64, or as many as keep a load's advance to 64 KB, inside `ainc`."""
    return min(64, 64 * KB // stride)


def loads(footprint: int, stride: int) -> int:
    return footprint // (burst(stride) * stride)


def image(name: str, action: str, stride: int) -> str:
    words = burst(stride)
    return f"""
image {name}(n, x)
    desc a0 = x walk=({stride}, {words})
    ainc a0 += {words * stride}
    seti s0 = n
    loop s0
        {action}
    {"vsync drain on=drain" if action.startswith("vdrain") else ""}
    halt
"""


def images() -> str:
    text = ""
    for s in STRIDES:
        text += image(f"vr{s}", "vfill a0 -> l1[0] rel\n        vsync fe on=fill", s)
        text += image(f"vw{s}", "vdrain a0 <- l1[0] rel", s)
    return text


def homes() -> str:
    """Each image walks lines 16 KB x HOMES apart, so all of it lands on one channel."""
    text = ""
    for k in range(HOMES):
        apart = ROTATION * HOMES
        text += f"""
image home{k}(n, x)
    desc a0 = x walk=(32, 2)
    ainc a0 += {k * ROTATION or 64}
    seti s0 = 1
    loop s0
        vfill a0 -> l1[0] rel
        vsync fe on=fill
    ainc a0 += {apart}
    seti s1 = n
    loop s1
        vfill a0 -> l1[0] rel
        vsync fe on=fill
    halt
"""
    return text


def elems(bytes_: int) -> int:
    return bytes_ // 2


def one(name: str, unit: int, image_: str, n: int, size: int) -> str:
    return f"""
fn {name}.l1(x: f16[{elems(size)}] @dram)
    send vc[{unit}]
        run {image_}({n}, x)
    barrier
"""


def two(name: str, image_: str, n: int, size: int) -> str:
    return f"""
fn {name}.l1(x: f16[{elems(size)}] @dram, y: f16[{elems(size)}] @dram)
    send vc[0]
        run {image_}({n}, x)
    send vc[1]
        run {image_}({n}, y)
    barrier
"""


def copy(name: str, count: int, stride: int, size: int) -> str:
    walk = f"({count}, {stride})"
    return f"""
fn {name}.l1(x: f16[{elems(size)}] @dram, y: f16[{elems(size)}] @dram)
    move
        copy w(x, {walk}) -> w(y, {walk})
"""


def kernels() -> str:
    text = ""
    for f in FOOTPRINTS:
        for s in STRIDES:
            n = loads(f, s)
            if n < 2 or n > 32768:
                continue
            tag = f"{f // KB}k_{s}"
            text += one(f"vr_{tag}", 0, f"vr{s}", n, f)
            text += one(f"vw_{tag}", 0, f"vw{s}", n, f)
            text += two(f"vr2_{tag}", f"vr{s}", n, f)
            text += two(f"vw2_{tag}", f"vw{s}", n, f)
            words = f // s
            if words <= 32768:
                text += copy(f"mv_{tag}", words, s, f)
    span = 64 * MB
    for k in range(HOMES):
        text += one(f"home_{k}", 0, f"home{k}", 512, span)
    return text


def main():
    pathlib.Path(sys.argv[1]).write_text(HEAD + images() + homes() + kernels(), "utf-8")


if __name__ == "__main__":
    main()
