"""Emit a board file (boards/<design>.json) from the image's Tcl config.

    python scripts/py/gen_board.py --ver v9t4            # boards/multimesh_v9t4.json
    python scripts/py/gen_board.py --ver v9 --check      # diff against the file

Every field comes from what the build consumed: the station map
(v8/50_addr_lit.tcl), the mesh wizard (VCO_D, VCO_M, DIV_*), the Xache and DRAM
knobs, MESHES and each die module's unit map (regen_tops.MANIFEST). A board
the driver reads is then the bitstream's own description, never a transcript.
"""

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "py"))

import gen_card
import gen_mesh
import regen_tops

BOARDS = ROOT / "boards"
#: The reference clock every mesh wizard divides (100 MHz board oscillator).
REF_MHZ = 100.0
#: The node's memory address width: the mesh id sits at [ADDR_W-4 +: 2]
#: (mag_ilink.v A_MESH_LO).
NODE_AW = 40
#: Profile rates as fractions of each output's built rate: 100/200 low, ship.
PROFILES = {"low": 1 / 3, "mid": 2 / 3, "ship": 1.0}
#: The mesh wizard's outputs in CLKOUT order (gen_card.py's DIV0, 20_clocks.tcl).
OUTPUTS = (
    ("noc", "DIV_MESH"),
    ("mat2x", "DIV_MAT2X"),
    ("vec", "DIV_VEC"),
    ("sys", "DIV_SYS"),
)
#: 64-bit JTAG beats a burst may carry (multimesh_v8t8 / v9 boards).
JTAG_BURST = 64
#: Keys a generated board adds that hand-written ones did not carry.
NEW_KEYS = ("units", "sys_ports")


def die_map(module: str) -> gen_mesh.Mesh:
    """The parsed unit map a die module was generated from."""
    base = module.removesuffix("_pump")
    for entry in regen_tops.MANIFEST:
        if entry[0] == base:
            text = (ROOT / regen_tops.MAPS / entry[1]).read_text(encoding="utf-8")
            return gen_mesh.Mesh(gen_mesh.parse_map(text))
    raise SystemExit(f"gen_board: {module} is not in regen_tops.MANIFEST")


def board(
    ver: str,
    die: str | None = None,
    compute: tuple | None = None,
    name: str | None = None,
) -> dict:
    """The board of image `ver`; with `die`, `compute` and `name`, the
    simulated card gen_card.py makes of it (`--sim-mesh die --compute ...`):
    every die's module `die`, nodes on the `compute` dies only."""
    c = gen_card.Config(ver)
    design = name or c.s("design_name")
    proj = c.s("proj_dir")
    dies = c.meshes()
    if die:
        dies = [(m, die) for m, _ in dies]
    if compute is not None:
        dies = [(m, mod) for m, mod in dies if m in compute]
    maps = {mod: die_map(mod) for _, mod in dies}
    if len({(tuple(m.cus), tuple(m.vecs), tuple(m.mags)) for m in maps.values()}) != 1:
        raise SystemExit("gen_board: the dies differ; a board describes one die shape")
    mesh = next(iter(maps.values()))

    vco = REF_MHZ / c.i("VCO_D") * float(c.s("VCO_M"))
    outputs = {
        name: {"index": k, "nominal_mhz": round(vco / c.i(div))}
        for k, (name, div) in enumerate(OUTPUTS)
    }
    profiles = {
        p: {name: round(o["nominal_mhz"] * f) for name, o in outputs.items()}
        for p, f in PROFILES.items()
    }
    win = int(c.s("MESH_WIN"))
    rb = c.i("KX_RB_BEATS")
    return {
        "name": design,
        "design": c.s("design_name") if name else design,
        "transport": "verilator" if name else "jtag",
        "meshes": len(dies),
        "vco_mhz": round(vco),
        "wizard_outputs": outputs,
        "profiles": profiles,
        "idle_profile": "low",
        "ctrl_stride": "0x10000",
        "ctrl_base": hex(int(c.s("CTRL_BASE"), 0)),
        "wizard_base": hex(int(c.s("WIZ_BASE"), 0)),
        "ddrctrl_base": "0x0",
        "ddrctrl_stride": hex(int(c.s("DDR_WIN"), 0)),
        "mem_window_shift": int(math.log2(win)),
        "mem_window_offset": 1,
        "dram_mesh_shift": NODE_AW - 4,
        "dram_flat_gb": c.i("DRAM_GB"),
        "dram_interleave_kb": (1 << c.i("KX_ILV_LG")) // 1024,
        "mem_words": c.i("DRAM_GB") * (1 << 30) // 32,
        "agent_at_offset_zero": True,
        # The JTAG manager's burst cap every board since v8t8 carries; below
        # one Xache reorder slot (KX_RB_BEATS 512-bit beats) at any setting.
        "max_burst_beats": min(JTAG_BURST, 8 * (rb or 64)),
        "chain": sorted(m for m, _ in dies),
        "bitstream": (
            "" if name else f"{proj}/{design}.runs/impl_1/{design}_wrapper.bit"
        ),
        "probes": "",
        "host_write_granule": c.i("FW") // 8,
        "host_write_replicates": False,
        "burst_read": True,
        "fetch_port": list(mesh.mags[-1]),
        "units": {
            "MG": [list(p) for p in mesh.cus],
            "VC": [list(p) for p in mesh.vecs],
        },
        "sys_ports": [list(p) for p in mesh.mags],
        "notes": (
            f"{design}: GENERATED by scripts/py/gen_board.py from "
            f"scripts/tcl/{ver}/00_config.tcl"
            + (f" as the simulated card (--die {die})" if name else "")
            + "; dies "
            + ", ".join(f"{m} {mod}" for m, mod in dies)
            + f" ({len(mesh.cus)} MG + {len(mesh.vecs)} VC each)."
        ),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ver", required=True)
    ap.add_argument("--check", action="store_true", help="diff against the board file")
    ap.add_argument("--die", help="a simulated card's die module (gen_card --sim-mesh)")
    ap.add_argument("--compute", help="its node dies, e.g. 0 (gen_card --compute)")
    ap.add_argument("--name", help="its board name")
    a = ap.parse_args()
    sim = (a.die, a.compute, a.name)
    if any(sim) and not all(sim):
        ap.error("--die, --compute and --name go together")
    compute = tuple(int(x) for x in a.compute.split(",")) if a.compute else None
    b = board(a.ver, a.die, compute, a.name)
    path = BOARDS / f"{b['name']}.json"
    if a.check:
        old = json.loads(path.read_text(encoding="utf-8"))
        diff = [
            k
            for k in sorted(set(old) | set(b))
            if k not in ("notes", *NEW_KEYS) and old.get(k) != b.get(k)
        ]
        for k in diff:
            print(f"{k}: file {old.get(k)!r}, generated {b.get(k)!r}")
        print(f"{path.name}: {'matches' if not diff else f'{len(diff)} fields differ'}")
        return 1 if diff else 0
    path.write_text(json.dumps(b, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
