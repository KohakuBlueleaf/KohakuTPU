def w(width, dw, idw):
    if width == "DW":
        return dw
    if width == "SW":
        return dw // 8
    if width == "IDW":
        return idw
    return width


def port_decl(prefix, fields, dw, idw, master_is_host):
    """Top-level ports for one host manager: the host DRIVES the station's S
    side, so an 'o' field of the station's M list is an INPUT here."""
    out = []
    for name, width, d in fields:
        n = w(width, dw, idw)
        dirn = "input " if (d == "o") == master_is_host else "output"
        vec = f"[{n - 1}:0] " if n > 1 else ""
        out.append(f"    {dirn} wire {vec}{prefix}_{name},")
    return out


def wire_decl(prefix, fields, dw, idw):
    out = []
    for name, width, _ in fields:
        n = w(width, dw, idw)
        vec = f"[{n - 1}:0] " if n > 1 else ""
        out.append(f"    wire {vec}{prefix}_{name};")
    return out


def conn(port_prefix, sig_prefix, fields):
    return [f".{port_prefix}_{name}({sig_prefix}_{name})" for name, _, _ in fields]


