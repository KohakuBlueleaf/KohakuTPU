def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="tests/system/v8t_card.v")
    ap.add_argument("--banks", type=int, default=8)
    ap.add_argument("--dram-words", type=int, default=1 << 16)
    a = ap.parse_args()
    text = emit(a.banks, a.dram_words)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(text, encoding="utf-8")
    print(f"wrote {a.out}: {text.count(chr(10))} lines")


if __name__ == "__main__":
    main()
