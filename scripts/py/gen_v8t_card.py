"""Emit tests/system/v8t_card.v: the multimesh_v8t block design as one Verilog
top for simulation -- the BD's own modules (ktpu_node_v8t x4, kx_pbd_4x4,
sb_bd_line4, xcvu13p_rst_tree) with the vendor IP replaced by the repo's
behavioural stand-ins (axi_ram for each DDR4, axil_ram for the two register
endpoints per die, axi_up32to64 for the width converter, kh_rst_sync for the
proc_sys_reset blocks) and the three host managers (JTAG 64-bit, XDMA 512-bit,
XDMA Lite) brought to the boundary for a harness to drive. Every clock of the
image is a port: the harness owns the fifteen domains at their real periods.

    python scripts/py/gen_v8t_card.py -o tests/system/v8t_card.v

The station map is v8t's (scripts/tcl/v8/50_addr_lit.tcl), computed here the
same way and emitted as the sized literals sb_bd_line4 takes.
"""

import argparse
from pathlib import Path

AW = 43
FULL = (1 << AW) - 1
NQ = 4
MESHES = 4
MESH_WIN = 1 << 40
CTRL_BASE, WIZ_BASE, DDR_WIN = 0x800000, 0x900000, 0x100000

# the Xache's 16 KB rotation: pairs (i, i+2) for i = 14..31, byte k of the
# 256-bit wrapper parameter is pair k
KX_ILV_LG, KX_HOME_LSB = 14, 32


def seg_tables():
    base, mask, xlt, dst, dprt = [], [], [], [], []
    for m in range(MESHES):
        base.append((m + 1) * MESH_WIN)
        mask.append(7 * MESH_WIN)
        xlt.append(0)
        dst.append(m)
        dprt.append(0)
        b = CTRL_BASE + m * 0x10000
        base.append(b)
        mask.append(FULL ^ 0xFFFF)
        xlt.append(b)
        dst.append(m)
        dprt.append(1)
        b = m * DDR_WIN
        base.append(b)
        mask.append(FULL ^ 0xFFFFF)
        xlt.append(b)
        dst.append(m)
        dprt.append(2)
        b = WIZ_BASE + m * 0x10000
        base.append(b)
        mask.append(FULL ^ 0xFFFF)
        xlt.append(b)
        dst.append(m)
        dprt.append(3)
    return base, mask, xlt, dst, dprt


def cat(vals, width):
    """Segment k at bits [k*width +: width], as v8_cat packs it."""
    v = 0
    for k, x in enumerate(vals):
        v |= (x & ((1 << width) - 1)) << (k * width)
    n = len(vals) * width
    return f"{n}'h{v:0{(n + 3) // 4}x}"


def swap_literal(offset):
    v = 0
    for k in range(KX_HOME_LSB - KX_ILV_LG):
        v |= (KX_ILV_LG + offset + k) << (8 * k)
    return f"256'h{v:064x}"


