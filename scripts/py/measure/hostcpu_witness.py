"""Byte-for-byte offline dispatch transcripts; these are NOT numeric model results."""

import argparse
import json
import os
import pickle
from pathlib import Path

from hseam import workload
from tinygrad import Tensor
from tinygrad.helpers import Context

from kohakutpu.application.ktpugrad import memo as M
from kohakutpu.application.ktpugrad import run as R
from kohakutpu.application.runtime import device as D

KNOBS = (
    "KTPU_PLAN_CACHE",
    "KOHAKUTPU_ADMISSION_CONTEXT",
    "KOHAKUTPU_ARENA_LOOKUP",
    "KOHAKUTPU_HOST_SUBMIT_CACHE",
)


def capture(args):
    for name in KNOBS:
        os.environ[name] = str(args.mode)
    with D.attached(
        D.Device(
            "offline",
            board="multimesh_v9t6",
            library="build/templates",
            library_only=True,
            classes=False,
        )
    ) as dev:
        dev.card.record()
        run, arrays = workload(args.workload)
        for _ in range(3):
            inputs = [Tensor(a, device="KTPU").realize() for a in arrays]
            with Context(TRAINING=int(args.workload.startswith("lenet"))):
                run(*inputs)
            dev.drain()
        events = dev.card.recorded()
        assert dev.counters["compile_calls"] == dev.counters["library_misses"] == 0
        counts = dict(dev.counters)
        dev.close()
    with args.output.open("wb") as f:
        pickle.dump(events, f)
    print(
        json.dumps(
            {
                "events": len(events),
                "counters": counts,
                "vector_memo": R._vector_choice.counts,
                "view_memo": R._view.counts,
                "cache_enabled": os.environ[M.ENV],
            }
        )
    )


def compare(args):
    # Only trusted transcripts generated by this local script are unpickled.
    with args.left.open("rb") as f:
        left = pickle.load(f)
    with args.right.open("rb") as f:
        right = pickle.load(f)
    assert len(left) == len(right), (len(left), len(right))
    for i, (a, b) in enumerate(zip(left, right, strict=True)):
        assert a == b, f"dispatch event {i} differs ({a[0]} vs {b[0]})"
    result = {
        "events": len(left),
        "byte_identical": True,
        "numeric": False,
        "meaning": "same wire packages, host writes and host read requests; kernels not executed",
    }
    args.output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(result))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    cap = commands.add_parser("capture")
    cap.add_argument("workload", choices=("lenet-eager", "vit-eager"))
    cap.add_argument("--mode", choices=(0, 1), type=int, required=True)
    cap.add_argument("--output", type=Path, required=True)
    diff = commands.add_parser("compare")
    diff.add_argument("left", type=Path)
    diff.add_argument("right", type=Path)
    diff.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    (capture if args.command == "capture" else compare)(args)


if __name__ == "__main__":
    main()
