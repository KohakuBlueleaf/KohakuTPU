"""Tables and vectors for tests/sru/lane/sru_plane_tb.v.

    python scripts/py/sru/fn_vectors.py

Writes to build/sru/: tab_<name>.hex (1,024 x 36-bit entries) and, one
vector a line `x k mode pre cs tab neg mrom want`, in blocks of 1,000:
fn_ram.hex (the RAM lane: every table of fn.TABLES in ORDER, then the
mantissa ROM, tab = its ORDER index), fn_rom.hex (the exp2 ROM lane and the
mantissa ROM) and fn_nofn.hex (a lane with no function front end: the
mantissa ROM alone). Also src/kohakutpu/sru/lane/sru_exp2_rom.vh and
sru_mant_rom.vh, the ROMs' contents. Prints each table's worst error
against the real function.
"""

import argparse
import math
import pathlib
import random

import e8
import fn

ROOT = pathlib.Path(__file__).resolve().parents[3]


def word(s, e, m):
    return (s << 23) | (e << 15) | m


#: The tables' order in the RAM lane's vectors (the bench's tab index); the
#: mantissa ROM's blocks carry index len(ORDER).
ORDER = ["exp2", "sigmoid", "phi", "recip", "rsqrt", "sqrt"]


def x_word(rng, mode):
    k = rng.randrange(8)
    if k == 0:
        return rng.choice([0, 0x800000, word(0, 255, 0), word(1, 255, 0), e8.NAN])
    if mode >= fn.MANT:
        # every exponent, both signs: a negative HALF is NaN, the edges overflow
        return word(rng.getrandbits(1), rng.randint(1, 254), rng.getrandbits(15))
    if mode == fn.FIX:
        e = rng.randint(110, 132)  # up to |x| ~ 32: both saturation edges
    else:
        e = rng.randint(100, 136)
    return word(rng.getrandbits(1), e, rng.getrandbits(15))


def line(x, k, mode, pre, cs, tab, neg, mrom, want):
    return f"{x:06x} {k:06x} {mode:x} {pre & 0x3F:02x} {cs:x} {tab:x} {neg:x} {mrom:x} {want:06x}"


def mrom_vector(rng, rom):
    """One mantissa-ROM vector: RCP (MANT NEG) or RSQRT (HALF NEG)."""
    mode = rng.choice([fn.MANT, fn.HALF])
    x, k = x_word(rng, mode), k_word(rng)
    want = fn.lane(x, k, mode, 0, None, neg=1, mrom=rom)
    return line(x, k, mode, rng.randrange(64), rng.randrange(4), len(ORDER), 1, 1, want)


def mant_rom_vh(table):
    ents, cs = table
    lines = [
        "// GENERATED by scripts/py/sru/fn_vectors.py -- the mantissa ROM: 1/m at",
        "// 0..127, 1/sqrt(m 2^r) at 256..511 (r = 0 first), 128 linear segments",
        "// each over m in [1, 2). Entry layout: sru_plane.v.",
        f"localparam [1:0] MANT_ROM_CS = 2'd{cs};",
        "function [35:0] mant_rom;",
        "    input [8:0] i;",
        "    begin",
        "        case (i)",
    ]
    for i, v in enumerate(ents):
        if (v >> 29) & 0x3F != fn.ZERO_ES & 0x3F:
            lines.append(f"            9'd{i}: mant_rom = 36'h{v:09x};")
    lines += [
        "            default: mant_rom = 36'h0;",
        "        endcase",
        "    end",
        "endfunction",
        "",
    ]
    return "\n".join(lines)


def k_word(rng):
    k = rng.randrange(6)
    if k == 0:
        return word(rng.getrandbits(1), rng.randint(0, 140), rng.getrandbits(15))
    if k == 1:
        return rng.choice([word(0, 255, 0), word(1, 255, 0), e8.NAN])
    return word(rng.getrandbits(1), rng.randint(120, 134), rng.getrandbits(15))


def worst(name, table, f, lo, hi, fix, rom=False, pre=0):
    """Worst relative error where |f| >= 2^-8, and worst absolute error."""
    rel = ab = 0.0
    for i in range(40000):
        u = lo + (hi - lo) * (i + 0.5) / 40000
        x = e8.encode(fn.Fraction(u).limit_denominator(1 << 30))
        y = float(e8.value(fn.lane(x, 0, fix, pre, table, rom)))
        ref = f(float(e8.value(x)))
        ab = max(ab, abs(y - ref))
        if abs(ref) >= 2.0**-8:
            rel = max(rel, abs(y - ref) / abs(ref))
    print(
        f"  {name:10s} rel (|f| >= 2^-8) 2^{math.log2(rel):.2f}  abs 2^{math.log2(ab):.2f}"
    )


def rom_vh(table):
    lines = [
        "// GENERATED by scripts/py/sru/fn_vectors.py -- exp2 over [0, 1) in 128",
        "// linear segments, the sru_plane ROM kind. Entry layout: sru_plane.v.",
        "function [35:0] exp2_rom;",
        "    input [6:0] i;",
        "    begin",
        "        case (i)",
    ]
    for i, v in enumerate(table):
        lines.append(f"            7'd{i}: exp2_rom = 36'h{v:09x};")
    lines += [
        "            default: exp2_rom = 36'h0;",
        "        endcase",
        "    end",
        "endfunction",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=60000)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()

    out = ROOT / "build" / "sru"
    out.mkdir(parents=True, exist_ok=True)

    tabs = {name: build() for name, build in fn.TABLES.items()}
    for name, (ents, cs) in tabs.items():
        (out / f"tab_{name}.hex").write_text("".join(f"{v:09x}\n" for v in ents))
        print(f"  {name:10s} cs {cs}")
    rom = fn.exp2_table(128)
    assert rom[1] == 0, "the ROM lane has no slope scale"
    (ROOT / "src/kohakutpu/sru/lane/sru_exp2_rom.vh").write_text(rom_vh(rom[0]))
    mrom = fn.mrom_table()
    (ROOT / "src/kohakutpu/sru/lane/sru_mant_rom.vh").write_text(mant_rom_vh(mrom))

    worst("exp2 1K", tabs["exp2"], lambda u: 2.0**u, -8, 8, False)
    worst("exp2 ROM", rom, lambda u: 2.0**u, -8, 8, False, rom=True)
    worst("sigmoid", tabs["sigmoid"], fn.sigmoid, -15.9, 15.9, True)
    worst("phi", tabs["phi"], fn.phi, -8, 7.9, True, pre=fn.PRE["phi"])

    rng = random.Random(args.seed)
    lines = []
    # Blocks of 1,000 cycle the tables in ORDER, then the mantissa ROM; MANT /
    # HALF blocks take either NEG (the golden model covers both).
    for blk in range(args.n // 1000):
        idx = blk % (len(ORDER) + 1)
        for _ in range(1000):
            if idx == len(ORDER):
                lines.append(mrom_vector(rng, mrom))
                continue
            name = ORDER[idx]
            mode, neg = fn.MODE[name]
            table = tabs[name]
            x, k = x_word(rng, mode), k_word(rng)
            pre = rng.choice([0, 0, 0, 1, -1, 3, -3])
            if mode >= fn.MANT:
                neg = rng.getrandbits(1)
            want = fn.lane(x, k, mode, pre, table, neg=neg)
            lines.append(line(x, k, mode, pre, table[1], idx, neg, 0, want))
    (out / "fn_ram.hex").write_text("\n".join(lines) + "\n")

    lines = []
    for blk in range(args.n // 1000):
        for _ in range(1000):
            if blk % 3 == 2:
                lines.append(mrom_vector(rng, mrom))
                continue
            x, k = x_word(rng, fn.EXP), k_word(rng)
            pre = rng.choice([0, 0, 0, 1, -1])
            want = fn.lane(x, k, fn.EXP, pre, rom, rom=True)
            lines.append(line(x, k, fn.EXP, pre, 0, 0, 0, 0, want))
    (out / "fn_rom.hex").write_text("\n".join(lines) + "\n")

    lines = [mrom_vector(rng, mrom) for _ in range(args.n // 3)]
    (out / "fn_nofn.hex").write_text("\n".join(lines) + "\n")
    print(f"{out} fn_ram.hex fn_rom.hex {args.n}, fn_nofn.hex {args.n // 3} vectors")


if __name__ == "__main__":
    main()
