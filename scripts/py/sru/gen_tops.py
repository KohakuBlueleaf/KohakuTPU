"""Generate the SRU mesh tops from src/kohakutpu/sru/top/ maps.

    python scripts/py/sru/gen_tops.py            # rewrite
    python scripts/py/sru/gen_tops.py --check    # fail if any is stale

Each top is the v9 die form (one node, staging, no CU/vector L2, per-domain
reset, pumped clusters) with `sru` tokens at the profile named per entry.
"""

import argparse
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "scripts" / "py"))

import gen_board
import gen_mesh
from sru import profiles

TOP = ROOT / "src" / "kohakutpu" / "sru" / "top"
_spec = importlib.util.spec_from_file_location("tokens_sru", TOP / "tokens_sru.py")
tokens_sru = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(tokens_sru)

# (module, map, profile)
MANIFEST = [
    ("ktpu_ship_1x2_4c2s_1m_nol2_pump", "mesh_1x2_4+2s.txt", "strong"),
]
# Simulated cards: board name -> (image, die module). The board is the image's
# (gen_board.py) with the die's units; units of kind "SR" are the SRUs.
BOARDS = {"sru_v9t7": ("v9t7", MANIFEST[0])}


def die_map(mapname):
    toks = tokens_sru.tokens()
    text = (TOP / mapname).read_text(encoding="utf-8")
    return gen_mesh.Mesh(gen_mesh.parse_map(text, set(toks)), set(toks))


def board(name):
    ver, (module, mapname, profile) = BOARDS[name]
    mesh = die_map(mapname)
    b = gen_board.board(ver)
    b["name"] = name
    b["bitstream"] = ""
    b["units"] = {
        "MG": [list(p) for p in mesh.cus],
        "SR": [list(p) for p in mesh.units["sru"]],
    }
    knobs = profiles.PROFILES[profile]
    b["sru"] = {
        k: knobs[k]
        for k in (
            "F_LANES",
            "H_TAPS",
            "HAS_FN",
            "TAB",
            "HAS_MANT",
            "FIN_RCP",
            "F16_IEEE",
        )
    }
    b["notes"] = (
        f"{name}: GENERATED by scripts/py/sru/gen_tops.py; the {ver} image with "
        f"every die {module} ({len(mesh.cus)} MG + {len(mesh.units['sru'])} SR, "
        f"profile {profile}). Simulation only."
    )
    return json.dumps(b, indent=2) + "\n"


def emit(module, mapname, profile):
    toks = tokens_sru.tokens(profiles.PROFILES[profile])
    mesh = die_map(mapname)
    return gen_mesh.emit(
        mesh,
        module,
        True,
        0,
        True,
        mat_pump=True,
        l2_mag=True,
        l2_cu=False,
        l2_vec=False,
        tokens=toks,
        split_reset=True,
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report, do not write")
    args = ap.parse_args()

    outs = [(TOP / "generated" / f"{m}.v", emit(m, f, p)) for m, f, p in MANIFEST]
    outs += [(ROOT / "boards" / f"{n}.json", board(n)) for n in BOARDS]
    stale = []
    for out, text in outs:
        if out.exists() and out.read_text(encoding="utf-8") == text:
            continue
        stale.append(out.name)
        if not args.check:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")

    verb = "stale" if args.check else "rewritten"
    print(
        f"{len(stale)} of {len(outs)} {verb}"
        + (": " + " ".join(stale) if stale else "")
    )
    sys.exit(1 if (args.check and stale) else 0)


if __name__ == "__main__":
    main()
