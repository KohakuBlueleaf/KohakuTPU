"""The SRU configuration map as the RTL reads it: the map and the scheduler are
`kohakutpu.compiler.isa.sru` (one table for the compiler, the goldens and the
header); this file writes the RTL header from it.

    python scripts/py/sru/cfg.py      # writes src/kohakutpu/sru/sru_cfg.vh
"""

import pathlib

from kohakutpu.compiler.isa.sru import (
    ADDR_BITS,
    ASRC,
    BSRC,
    FIN_BASE,
    FIN_DEPTH,
    LDEP,
    OP_BASE,
    OP_DEPTH,
    OP_STRIDE,
    PASS_BASE,
    PASS_STRIDE,
    SRC,
    TAPS,
    WLEAD,
    F,
    G,
    O,
    P,
    pack,
    schedule,
)

ROOT = pathlib.Path(__file__).resolve().parents[3]

__all__ = [
    "ADDR_BITS",
    "ASRC",
    "BSRC",
    "FIN_BASE",
    "FIN_DEPTH",
    "LDEP",
    "OP_BASE",
    "OP_DEPTH",
    "OP_STRIDE",
    "PASS_BASE",
    "PASS_STRIDE",
    "SRC",
    "TAPS",
    "WLEAD",
    "F",
    "G",
    "O",
    "P",
    "header",
    "pack",
    "schedule",
]


def header():
    """Verilog-2001 macros (no token pasting): `SRU_G_<field> and
    `SRU_P_<field>(pass) slice the including module's cfg[]; `SRU_O_<field>(x)
    and `SRU_F_<field>(x) slice an op-store / finalise word bundle."""
    out = [
        "// GENERATED by scripts/py/sru/cfg.py -- the SRU configuration map.",
        "// `SRU_G_<field> and `SRU_P_<field>(pass) slice the including module's cfg[];",
        "// `SRU_O_<field>(x) slices an op's 128-bit word bundle {w3, w2, w1, w0}.",
        f"`define SRU_CFG_AW {ADDR_BITS}",
        f"`define SRU_OP_BASE {OP_BASE}",
        f"`define SRU_OP_DEPTH {OP_DEPTH}",
        f"`define SRU_FIN_BASE {FIN_BASE}",
        f"`define SRU_FIN_DEPTH {FIN_DEPTH}",
        f"`define SRU_LDEP {LDEP}",
    ]
    for name, (a, lo, w) in G.items():
        out.append(f"`define SRU_G_{name} cfg[{a}][{lo + w - 1}:{lo}]")
    for name, (a, lo, w) in P.items():
        out.append(
            f"`define SRU_P_{name}(p) cfg[{PASS_BASE} + {PASS_STRIDE} * (p) + {a}][{lo + w - 1}:{lo}]"
        )
    for name, (a, lo, w) in O.items():
        b = 32 * a + lo
        out.append(f"`define SRU_O_{name}(x) x[{b + w - 1}:{b}]")
    for name, code in ASRC.items():
        out.append(f"`define SRU_ASRC_{name} {code}")
    for name, code in BSRC.items():
        out.append(f"`define SRU_BSRC_{name} {code}")
    for name, (lo, w) in F.items():
        out.append(f"`define SRU_F_{name}(x) x[{lo + w - 1}:{lo}]")
    for name, code in SRC.items():
        out.append(f"`define SRU_SRC_{name} {code}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = ROOT / "src" / "kohakutpu" / "sru" / "sru_cfg.vh"
    path.write_text(header())
    print(path)
